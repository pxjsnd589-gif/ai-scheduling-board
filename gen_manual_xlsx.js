// ---- 样式 ----
const FONT = '微软雅黑';
const C_HEAD = '4F5DAA';      // 表头深蓝紫
const C_BAND = 'F4F5FA';      // 隔行浅底
const C_WARN = 'FFF4E0';      // 提醒黄
const C_OK = 'E8F5EE';        // 可自助绿
