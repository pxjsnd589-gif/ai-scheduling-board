const bd = { style: 'thin', color: { rgb: 'D8DAE5' } };
const BORDER = { top: bd, bottom: bd, left: bd, right: bd };

function head(t) {
  return {
    v: t, t: 's',
    s: {
      font: { name: FONT, sz: 11, bold: true, color: { rgb: 'FFFFFF' } },
      fill: { fgColor: { rgb: C_HEAD } },
      alignment: { horizontal: 'center', vertical: 'center', wrapText: true },
      border: BORDER
    }
  };
}
function cell(t, opt) {
  opt = opt || {};
  return {
    v: t == null ? '' : t, t: 's',
    s: {
      font: { name: FONT, sz: 10, bold: !!opt.bold, color: { rgb: opt.color || '2C2C2A' } },
      fill: opt.bg ? { fgColor: { rgb: opt.bg } } : undefined,
      alignment: { vertical: 'top', wrapText: true, horizontal: opt.center ? 'center' : 'left' },
      border: BORDER
    }
  };
}
function title(t) {
  return {
    v: t, t: 's',
    s: {
      font: { name: FONT, sz: 14, bold: true, color: { rgb: '2C2C4A' } },
      alignment: { vertical: 'center' }
    }
  };
}
function note(t) {
  return {
    v: t, t: 's',
    s: {
      font: { name: FONT, sz: 10, color: { rgb: '6A6A7A' } },
      alignment: { vertical: 'center', wrapText: true }
    }
  };
}

const wb = { SheetNames: [], Sheets: {} };
function addSheet(name, aoa, cols, rows, merges) {
  const ws = XLSX.utils.aoa_to_sheet(aoa);
  ws['!cols'] = cols;
  if (rows) ws['!rows'] = rows;
  if (merges) ws['!merges'] = merges;
  wb.SheetNames.push(name);
  wb.Sheets[name] = ws;
}

